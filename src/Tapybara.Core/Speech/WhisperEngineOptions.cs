namespace Tapybara.Core.Speech;

/// <summary>Настройки движка распознавания.</summary>
/// <remarks>
/// <c>record</c> с <c>init</c>-свойствами: объект собирается один раз при
/// создании и дальше неизменяем. Для настроек это то, что надо, — никто не
/// поменяет язык у движка из-под работающего распознавания.
/// </remarks>
public sealed record WhisperEngineOptions
{
    /// <summary>Путь к ggml-модели. <c>required</c> — без него объект не создать.</summary>
    public required string ModelPath { get; init; }

    /// <summary>Язык распознавания. <c>"auto"</c> — определять по звуку.</summary>
    public string Language { get; init; } = "ru";

    /// <summary>
    /// Подсказка словаря: биасит распознавание в сторону нужных терминов.
    /// Не команда для модели, а «затравка» контекста — сюда идут имена
    /// продуктов и жаргон, которые ASR иначе коверкает.
    /// </summary>
    public string? Prompt { get; init; }

    /// <summary>
    /// Ширина луча при декодировании. <c>1</c> — жадный поиск.
    /// </summary>
    /// <remarks>
    /// Жадный поиск на каждом шаге берёт самый вероятный токен и назад не
    /// возвращается: одна неудачная догадка тянет за собой всю фразу. Так
    /// английское «permit denied», начатое с неверного первого слова,
    /// достраивалось до «Хермит отказал» — модель не ошиблась в звуке, она
    /// не смогла передумать.
    /// <para>
    /// Beam search держит несколько гипотез сразу и выбирает лучшую по сумме
    /// вероятностей всей фразы, поэтому одно плохое начало отбрасывается
    /// вместе со своим продолжением. Это значение по умолчанию у эталонного
    /// Whisper, и разница видна ровно там, где она нужна: имена, термины,
    /// окончания.
    /// </para>
    /// <para>
    /// Замер на тридцатисекундном образце, large-v3-turbo, Vulkan, RTX 3060:
    /// жадный поиск — 0,46 с, луч 5 — 0,70 с. Полтора раза, и на этом же
    /// образце жадный воспроизводимо ломает счёт вслух («десять, девять,
    /// а за семь, семь, шесть»), а луч считает верно. Двести сорок
    /// миллисекунд за исправленную ошибку — сделка, которую стоит заключать
    /// по умолчанию.
    /// </para>
    /// <para>
    /// Цена растёт с шириной луча, поэтому это настройка, а не константа:
    /// на слабой видеокарте и часовом звонке выбор может быть другим.
    /// </para>
    /// </remarks>
    public int BeamSize { get; init; } = DefaultBeamSize;

    /// <summary>Ширина луча по умолчанию — она же продуктовая.</summary>
    /// <remarks>
    /// Константа существует ради замеров: инструмент, который
    /// подставляет собственное значение вместо продуктового, меряет
    /// то, чего у пользователя нет.
    /// </remarks>
    public const int DefaultBeamSize = 5;

    /// <summary>
    /// Стартовая температура декодирования.
    /// </summary>
    /// <remarks>
    /// Ноль — детерминированный первый проход: один и тот же звук даёт один и
    /// тот же текст. Whisper повышает температуру сам, если результат не
    /// прошёл пороги (энтропия, средняя логарифмическая вероятность) — этот
    /// откат и вытаскивает из циклов повторов, и его мы не трогаем.
    /// <para>
    /// Задано явно, хотя у Whisper.net есть своё умолчание: по документации
    /// сборки оно равно 0.2f, то есть уже случайное. Полагаться в таком месте
    /// на чужое умолчание — значит согласиться, что распознавание одного и
    /// того же файла дважды даёт разный текст.
    /// </para>
    /// </remarks>
    public float Temperature { get; init; }

    /// <summary>Считать на GPU. Выключать имеет смысл только для сравнения скорости.</summary>
    public bool UseGpu { get; init; } = true;

    /// <summary>
    /// Flash attention — заметно быстрее и экономнее по памяти на длинных
    /// записях. Поддерживается CUDA-сборкой; на неподдерживающем бэкенде
    /// whisper.cpp тихо откатывается на обычное внимание.
    /// </summary>
    public bool UseFlashAttention { get; init; } = true;

    /// <summary>
    /// Число потоков CPU. <c>null</c> — оставить процессору пару ядер
    /// на всё остальное, чтобы система не задыхалась во время распознавания.
    /// </summary>
    public int? Threads { get; init; }

    /// <summary>Через сколько простоя выгружать модель из памяти.</summary>
    public TimeSpan IdleUnloadAfter { get; init; } = TimeSpan.FromMinutes(10);

    /// <summary>Фактическое число потоков с учётом <c>null</c>-значения по умолчанию.</summary>
    public int EffectiveThreads => Threads ?? Math.Max(2, Environment.ProcessorCount - 2);
}
