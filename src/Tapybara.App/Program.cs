using Velopack;

namespace Tapybara.App;

/// <summary>Точка входа.</summary>
/// <remarks>
/// <para>
/// Свой <c>Main</c>, а не тот, что WPF генерирует из App.xaml. При установке,
/// обновлении и удалении Velopack запускает Tapybara.exe с особыми
/// аргументами, делает своё и сразу завершает процесс. Это должно случиться
/// раньше всего остального: раньше мьютекса единственного экземпляра, трея и
/// хоткеев — иначе «запуск ради удаления» разбудил бы работающую копию или
/// успел бы занять горячую клавишу.
/// </para>
/// <para>
/// Там же применяется скачанное обновление: если в прошлый раз оно
/// скачалось, Velopack ставит его здесь и перезапускает программу. Момент
/// выбран не случайно — при старте ничего не пишется и не распознаётся, и
/// обновление не может оборвать запись звонка.
/// </para>
/// <para>
/// В сборке из zip и при запуске из среды разработки <c>Run</c> ничего не
/// делает: программа не установлена, и применять нечего.
/// </para>
/// </remarks>
internal static class Program
{
    [STAThread]
    private static void Main()
    {
        VelopackApp.Build().Run();

        var app = new App();
        app.InitializeComponent();
        app.Run();
    }
}
